#include "Backend.hpp"

////////////////////////////////////////////////////////////

void Backend::update()
{
    if (_dirty)
    {
        recompute(); // recompute
        _dirty = false;
    }
}

////////////////////////////////////////////////////////////

void Backend::resize()
{
    onResize();
    _dirty = true;
}

