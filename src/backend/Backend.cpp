#include "Backend.hpp"

////////////////////////////////////////////////////////////

void Backend::update()
{
    if (_dirty)
    {
        submitJob(); // recompute
        _dirty = false;
    }
}

////////////////////////////////////////////////////////////

void Backend::resize()
{
    onResize();
    _dirty = true;
}

////////////////////////////////////////////////////////////

void Backend::changeFractal()
{
    _dirty = true;
    onFractalChange();
}

////////////////////////////////////////////////////////////

void Backend::markDirty()
{
    _dirty = true;
}

